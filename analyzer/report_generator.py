"""JSON and Markdown report generation from an analysis result."""

from __future__ import annotations

import json
import re
from typing import Any

from .models import SEVERITIES, SOURCE_QUALITY, SOURCE_SECURITY


def generate_json_report(result: dict[str, Any]) -> str:
    """Complete machine-readable report."""
    return json.dumps(result, indent=2, ensure_ascii=False)


def _fence(text: str, language: str = "") -> str:
    """Fenced code block that survives backticks inside ``text``."""
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}{language}\n{text}\n{ticks}"


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: list[list[object]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return lines


def _finding_section(index: int, finding: dict[str, Any]) -> list[str]:
    lines = [
        f"### {index}. [{finding['severity']}] {finding['title']} (line {finding['line']})",
        "",
        f"- **ID:** {finding['finding_id']}",
        f"- **Severity / Confidence:** {finding['severity']} / {finding['confidence']}",
        f"- **Category:** {finding['category']}",
    ]
    if finding.get("cwe"):
        lines.append(f"- **CWE:** {finding['cwe']}")
    if finding.get("more_info"):
        lines.append(f"- **Reference:** {finding['more_info']}")
    lines += ["", finding["description"], ""]
    if finding.get("code_snippet"):
        lines += [_fence(finding["code_snippet"], "python"), ""]
    lines += [f"**Remediation:** {finding['remediation']}", ""]

    ai = finding.get("ai_explanation")
    if ai:
        origin = f"Ollama ({ai.get('model')})" if ai.get("source") == "ollama" else "built-in guidance"
        lines += [
            f"**Explanation ({origin}):** {ai['explanation']}",
            "",
            f"**Impact:** {ai['impact']}",
            "",
            f"**Safer approach:** {ai['safer_approach']}",
            "",
        ]
        if ai.get("corrected_code"):
            lines += [_fence(ai["corrected_code"], "python"), ""]
        if ai.get("note"):
            lines += [f"_{ai['note']}_", ""]
    return lines


def generate_markdown_report(result: dict[str, Any]) -> str:
    """Human-readable report suitable for pull requests and audits."""
    summary = result["summary"]
    findings = result["findings"]
    bandit = result.get("scanners", {}).get("bandit", {})
    ai = result.get("ai", {})

    lines = [
        "# CodeSentinel AI - Analysis Report",
        "",
        *_table(
            ["Field", "Value"],
            [
                ["File", result["filename"]],
                ["Analysed at (UTC)", result["analyzed_at"]],
                ["Lines of code", result["lines"]],
                ["SHA-256", result["sha256"]],
                ["Bandit", f"v{bandit['version']}" if bandit.get("ran") else "not run"],
                ["AI explanations", f"{ai.get('model')} ({ai.get('ai_generated', 0)} LLM, {ai.get('fallback', 0)} built-in)" if ai.get("enabled") else "disabled"],
            ],
        ),
        "",
        "## Summary",
        "",
        f"**{summary['total']} findings** - {summary['security']} security, {summary['quality']} code quality.",
        "",
        *_table(["Severity", "Count"], [[sev, summary["by_severity"].get(sev, 0)] for sev in SEVERITIES]),
        "",
    ]
    if summary["by_category"]:
        lines += [*_table(["Category", "Count"], [[c, n] for c, n in summary["by_category"].items()]), ""]

    for source, heading in (
        (SOURCE_SECURITY, "Security vulnerabilities (Bandit)"),
        (SOURCE_QUALITY, "Code quality warnings (AST)"),
    ):
        group = [f for f in findings if f["source"] == source]
        lines += [f"## {heading} ({len(group)})", ""]
        if not group:
            lines += ["_No findings._", ""]
        for number, finding in enumerate(group, start=1):
            lines += _finding_section(number, finding)

    if result.get("warnings"):
        lines += ["## Scan notes", "", *[f"- {w}" for w in result["warnings"]], ""]
    if ai.get("error"):
        lines += ["## AI notes", "", f"- {ai['error']}", ""]

    lines += [
        "---",
        f"_Generated by CodeSentinel AI v{result['version']}. Static analysis only - the analysed code was never executed. "
        "Review all findings and suggested fixes manually._",
        "",
    ]
    return "\n".join(lines)
